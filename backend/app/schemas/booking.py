"""Pydantic schemas for the Phase 4 booking engine HTTP API and DTO interop."""

from __future__ import annotations

from datetime import date, datetime
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field


class SlotResponse(BaseModel):
    """Available appointment slot representation."""

    model_config = ConfigDict(from_attributes=True)

    start_at: datetime
    end_at: datetime
    duration_minutes: int


class AvailabilityResponse(BaseModel):
    """Response containing available slots for a given clinic and service across a date range."""

    clinic_id: int
    service_id: int
    from_date: date
    to_date: date
    slots: list[SlotResponse]


class ProposeBookingRequest(BaseModel):
    """Payload to propose a new appointment slot."""

    clinic_id: int = Field(default=1, description="Clinic identifier")
    service_id: int = Field(..., description="Service identifier")
    session_id: str = Field(..., description="Voice/caller session identifier")
    created_turn_id: int = Field(..., description="Caller turn counter when proposal was requested")
    caller_name: str = Field(..., min_length=1, description="Caller's full name")
    caller_phone: str = Field(..., description="Caller's phone number")
    caller_email: str | None = Field(default=None, description="Optional caller email")
    start_at: datetime = Field(..., description="Requested slot start timestamp (timezone-aware)")


class ProposalResponse(BaseModel):
    """Response schema for an expiring booking proposal."""

    model_config = ConfigDict(from_attributes=True)

    id: UUID
    clinic_id: int
    service_id: int
    service_name: str
    session_id: str
    caller_name: str
    caller_phone: str
    caller_email: str | None
    start_at: datetime
    end_at: datetime
    duration_minutes: int
    buffer_minutes: int
    state: str
    expires_at: datetime


class ConsentAuthorizationRequest(BaseModel):
    """Signed consent token payload generated by the server consent coordinator."""

    session_id: str
    action_type: str
    target_id: str
    authorized_turn_id: int
    challenge_id: str
    nonce: str
    created_at: datetime
    expires_at: datetime
    ttl_seconds: int
    signature: str
    expected_target_version: int | None = None


class ConfirmBookingRequest(BaseModel):
    """Payload to confirm an existing booking proposal with signed consent."""

    voice_session_id: str
    consent: ConsentAuthorizationRequest


class AppointmentResponse(BaseModel):
    """Response schema for a confirmed appointment."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    clinic_id: int
    service_id: int
    service_name: str
    caller_name: str
    caller_phone: str
    caller_email: str | None
    start_at: datetime
    end_at: datetime
    duration_minutes: int
    buffer_minutes: int
    status: str
    version: int


class VerifyCallerRequest(BaseModel):
    """Payload to verify caller identity using phone and last 4 digits."""

    session_id: str
    clinic_id: int = 1
    appointment_id: int | None = None
    phone: str
    last4: str


class VerificationResponse(BaseModel):
    """Response schema for caller identity verification outcome."""

    success: bool
    handoff_required: bool
    advisory_message: str | None = None
    appointment: AppointmentResponse | None = None
